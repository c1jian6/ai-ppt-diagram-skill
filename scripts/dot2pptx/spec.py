"""Turn a small JSON description into DOT source.

The JSON format is deliberately shallow so that a diagram can be authored by
hand, generated by a script, or written by an assistant in one pass::

    {
      "title": "训练流水线",
      "theme": "ocean",
      "direction": "LR",
      "nodes": {
        "raw":  "原始数据",
        "train": {"label": "训练", "tone": "primary", "sub": "GPU × 8"}
      },
      "edges": ["raw -> train", {"from": "train", "to": "eval", "label": "每轮"}],
      "clusters": [{"label": "离线阶段", "nodes": ["raw", "train"]}],
      "ranks": [["train", "eval"]]
    }
"""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

from . import themes

GRAPH_DEFAULTS = {
    "direction": "TB",
    "engine": "dot",
    "splines": None,          # None -> "spline" (image) / "ortho" (native shapes)
    "nodesep": 0.45,
    "ranksep": 0.55,
    "pad": 0.12,
    "fontsize": 12.0,
    "node_fontsize": 12.5,
    "edge_fontsize": 10.5,
    "node_penwidth": 1.2,
    "edge_penwidth": 1.3,
    "dpi": 300,
}

#: shape alias -> (graphviz shape, extra style prefix, margin)
