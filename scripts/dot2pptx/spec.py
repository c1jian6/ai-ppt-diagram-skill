def _node_stmt(node: dict, theme: dict, graph: dict, custom: dict | None = None) -> str:
    tone = themes.tone(theme, node["tone"], custom)
    shape_name, style_prefix, margin = _style_prefix(node["shape"])
    fill = tone.get("fill", "none")

    attrs = []
    if node["html"]:
        attrs.append("label=<" + str(node["label"]) + ">")
    elif node["bullets"]:
        attrs.append("label=" + _bullet_label(node, tone, theme, graph["node_fontsize"]))
    elif node["sub"]:
        attrs.append(
            "label="
            + _html_label(node["label"], node["sub"], tone, theme, graph["node_fontsize"])
        )
    else:
        attrs.append(f"label={_plain_label(node['label'])}")

    attrs.append(f"shape={shape_name}")
    if shape_name not in ("plaintext",):
        style = style_prefix + "filled"
        attrs.append(f'style="{style}"')
        if fill and fill != "none":
            attrs.append(f'fillcolor="{fill}"')
        else:
            attrs.append('fillcolor="none"')
        attrs.append(f'color="{tone.get("stroke", "#999999")}"')
        attrs.append(f'fontcolor="{tone.get("font", "#111111")}"')
        attrs.append(f'penwidth={_num(graph["node_penwidth"])}')
    else:
        attrs.append(f'fontcolor="{tone.get("font", "#111111")}"')

    if margin and margin != "0":
        attrs.append(f'margin="{margin}"')
    if node["width"]:
        attrs.append(f"width={_num(node['width'])}")
    if node["height"]:
        attrs.append(f"height={_num(node['height'])}")

    return f"  {_id(node['id'])} [{', '.join(attrs)}];"


def _edge_stmt(edge: dict, theme: dict, graph: dict, custom: dict | None = None) -> str:
    color = themes.edge_colour(theme, edge["tone"], custom) or theme["edge"]["color"]

    attrs = []
    if edge["label"]:
        attrs.append(f"label={_plain_label(edge['label'])}")
    attrs.append(f'color="{color}"')
    attrs.append(f'fontcolor="{theme["edge"]["font"]}"')

    style = "invis" if edge["hidden"] else (str(edge["style"]).lower() if edge["style"] else None)
    if style:
        if style in ("bold", "thick"):
            attrs.append(f"penwidth={_num(float(graph['edge_penwidth']) * 1.7)}")
        else:
            attrs.append(f'style="{style}"')
    else:
        attrs.append(f'penwidth={_num(graph["edge_penwidth"])}')

    if edge["arrow"]:
        arrow = ARROWS.get(str(edge["arrow"]).lower())
        if arrow is None:
            raise ValueError(f"unknown arrow {edge['arrow']!r}; available: {', '.join(ARROWS)}")
        attrs.append(f"arrowhead={arrow}")
    if edge["minlen"] is not None:
        attrs.append(f"minlen={_num(edge['minlen'])}")
    if edge["weight"] is not None:
        attrs.append(f"weight={_num(edge['weight'])}")
    if edge["constraint"] is False:
        attrs.append("constraint=false")

    return f"  {_id(edge['from'])} -> {_id(edge['to'])} [{', '.join(attrs)}];"


def build_dot(slide: dict, theme: dict, mode: str = "image") -> str:
    """Return DOT source for a normalised *slide*."""
    graph = dict(slide["graph"])
    if not graph.get("splines"):
        graph["splines"] = "ortho" if mode == "native" else "spline"

    engine = str(graph.get("engine") or "dot").lower()
    head = [
        "digraph G {",
        "  graph ["
        + ", ".join(
            [
                f"rankdir={graph['direction']}",
                'bgcolor="transparent"',
                f'pad="{_num(graph["pad"])}"',
                f'nodesep="{_num(graph["nodesep"])}"',
                f'ranksep="{_num(graph["ranksep"])}"',
                f'fontname="{themes.FONT_DEFAULT}"',
                f"fontsize={_num(graph['fontsize'])}",
                f"splines={graph['splines']}",
                "outputorder=edgesfirst",
            ]
            + (["overlap=false"] if engine in ("neato", "fdp", "sfdp") else [])
        )
        + "];",
        "  node ["
        + ", ".join(
            [
                "shape=box",
                "style=filled",
                f'fillcolor="{theme["node"]["fill"]}"',
                f'color="{theme["node"]["stroke"]}"',
                f'fontcolor="{theme["node"]["font"]}"',
                f'fontname="{themes.FONT_DEFAULT}"',
                f"fontsize={_num(graph['node_fontsize'])}",
                f"penwidth={_num(graph['node_penwidth'])}",
                'margin="0.16,0.07"',
            ]
        )
        + "];",
        "  edge ["
        + ", ".join(
            [
                f'color="{theme["edge"]["color"]}"',
                f'fontcolor="{theme["edge"]["font"]}"',
                f'fontname="{themes.FONT_DEFAULT}"',
                f"fontsize={_num(graph['edge_fontsize'])}",
                f"penwidth={_num(graph['edge_penwidth'])}",
                "arrowsize=0.7",
            ]
        )
        + "];",
    ]

    custom = slide.get("tones") or {}
    statements = {node["id"]: _node_stmt(node, theme, graph, custom) for node in slide["nodes"]}

    body: list[str] = []
    emitted: set[str] = set()
    for cluster in slide["clusters"]:
        fill = theme["cluster"]["fill"]
        if cluster["tone"]:
            tone = themes.tone(theme, cluster["tone"], custom)
            fill = tone.get("fill", fill)
            stroke = tone.get("stroke", theme["cluster"]["stroke"])
        else:
            stroke = theme["cluster"]["stroke"]
        body.append(f"  subgraph cluster_{cluster['id']} {{")
        body.append(f"    label={_plain_label(cluster['label'])};")
        body.append("    labeljust=l;")
        body.append(f"    fontsize={_num(max(graph['edge_fontsize'], 10.0))};")
        body.append(f'    fontcolor="{theme["cluster"]["font"]}";')
        body.append(f'    color="{stroke}";')
        body.append(f'    style="{cluster["style"]}";')
        body.append(f'    fillcolor="{fill if fill and fill != "none" else "none"}";')
        body.append("    margin=14;")
        for member in cluster["members"]:
            if member in emitted:
                continue
            body.append("  " + statements[member])
            emitted.add(member)
        body.append("  }")

    for node in slide["nodes"]:
        if node["id"] not in emitted:
            body.append(statements[node["id"]])
            emitted.add(node["id"])

    for edge in slide["edges"]:
        body.append(_edge_stmt(edge, theme, graph, custom))

    for group in slide["ranks"]:
        if group:
            body.append("  { rank=same; " + "; ".join(_id(member) for member in group) + "; }")

    return "\n".join(head + body + ["}"]) + "\n"


def graph_size(dot_text: str, engine: str | None = None) -> tuple[float, float]:
    """Return the drawing size in points (width, height)."""
    from . import gv

    data = gv.layout_json(dot_text, engine=engine)
    bb = data.get("bb")
    if bb:
        values = [float(part) for part in str(bb).split(",")]
        if len(values) == 4:
            return values[2] - values[0], values[3] - values[1]
    width = float(str(data.get("width", "0")).replace("in", "") or 0) * 72
    height = float(str(data.get("height", "0")).replace("in", "") or 0) * 72
    return width, height
